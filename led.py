def create_presentation():
    prs = Presentation()

    # Add a title slide
    title_slide_layout = prs.slide_layouts[0]
    slide = prs.slides.add_slide(title_slide_layout)
    title = slide.shapes.title
    subtitle = slide.placeholders[1]
    title.text = "Light-Emitting Diodes (LEDs)"
    subtitle.text = "An Overview of LED Technology\nGenerated by Aura AI"

    # Add content slides
    for title_text, bullets in slides:
        add_bulleted_slide(prs, title_text, bullets)

    # Save the presentation
    output_filename = "LED_Presentation.pptx"
    prs.save(output_filename)
    print(f"Presentation saved as {output_filename}")

if __name__ == "__main__":
    create_presentation()