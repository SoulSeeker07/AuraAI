from pptx import Presentation
from pptx.util import Pt
from pptx.dml.color import RGBColor

# ------------------------------------------------------------------
# Helper: add a slide with a title and a bulleted list
# ------------------------------------------------------------------
def add_bulleted_slide(prs, title_text, bullet_items):
    """Create a slide with a title and a bullet list."""
    # Use layout 1 = Title & Content
    slide_layout = prs.slide_layouts[1]
    slide = prs.slides.add_slide(slide_layout)

    # Title
    slide.shapes.title.text = title_text

    # Content placeholder (bulleted list)
    tf = slide.placeholders[1].text_frame

    for i, txt in enumerate(bullet_items):
        # First paragraph already exists; subsequent ones need to be added
        p = tf.paragraphs[i] if i < len(tf.paragraphs) else tf.add_paragraph()
        p.text = txt
        p.level = 0
        p.font.size = Pt(18)
        p.font.name = "Calibri"
        p.font.color.rgb = RGBColor(0, 0, 0)

# ------------------------------------------------------------------
